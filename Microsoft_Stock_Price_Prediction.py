import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeRegressor

#Make the settings for the images
sns.set()
plt.style.use('fivethirtyeight')

#Read the dataset
data = pd.read_csv("MSFT.csv")
print(data.head())

#Create a chart showing Microsoft stock prices
plt.figure(figsize=(10, 4))
plt.title("Microsoft Stock Prices")
plt.xlabel("Date")
plt.ylabel("Close")
plt.plot(data["Close"])
plt.show()

#Examining the correlation between variables in the data set
print(data.corr(numeric_only=True))
sns.heatmap(data.corr(numeric_only=True))
plt.show()

#Determining the input and output variables for our model
x = data[["Open", "High", "Low"]]
y = data["Close"]

#Converting to numpy arrays
x = x.to_numpy()
y = y.to_numpy()
y = y.reshape(-1, 1)

#Splitting the dataset into training and test sets
xtrain, xtest, ytrain, ytest = train_test_split(x, y, test_size=0.2, random_state=42)

#Build and train the decision tree model
model = DecisionTreeRegressor()
model.fit(xtrain, ytrain)

#Making predictions on the test set
ypred = model.predict(xtest)

#Converting predictions to a dataframe
predictedData = pd.DataFrame(data={"Predicted Rate": ypred})

#Creating data frame of real values
realValues = {'Real Price':[239.40, 241.69, 241.26, 236.11, 238.70]}
lastData = pd.DataFrame(realValues)

#Creating the table where we compare the actual values with the estimated values generated by the machine
lastData["Predicted Rate"] = predictedData["Predicted Rate"]
lastData["Price Diff"] = lastData["Real Price"] - predictedData["Predicted Rate"]
lastData["Accuracy Rate"] = 100 - (abs(lastData["Price Diff"]) / lastData["Real Price"]* 100)
lastData = lastData.map(lambda x: '{:.2f}'.format(x))

#Create the table plot
fig, ax = plt.subplots()
ax.axis('off')
table = ax.table(cellText=lastData.values, colLabels=lastData.columns, loc='center')

#Adjust the layout and display the plot
plt.tight_layout()
plt.show()